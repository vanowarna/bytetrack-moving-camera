def _deep_merge(base: dict, over: dict) -> dict:
    out = dict(base)
    for k, v in over.items():
        out[k] = _deep_merge(out[k], v) if isinstance(v, dict) and isinstance(out.get(k), dict) else v
    return out


def _read_yaml(path: Path) -> dict:
    """Read a YAML config; `base: other.yaml` (relative to this file) is loaded first and overridden."""
    with open(path, encoding="utf-8") as f:
        cfg = yaml.safe_load(f) or {}
    if "base" in cfg:
        parent = _read_yaml((path.parent / cfg.pop("base")).resolve())
        cfg = _deep_merge(parent, cfg)
    return cfg


def load_config(path: str | Path) -> dict:
    """Load a run config (YAML). Supports `base:` inheritance; `seqs: all` expands to the 7 sequences."""
    path = Path(path)
    cfg = _read_yaml(path)
    seqs = cfg.get("seqs", "all")
    if seqs == "all":
        seqs = list(SEQS)
    unknown = [s for s in seqs if s not in SEQS]
    if unknown:
        raise ValueError(f"Unknown sequences in {path}: {unknown}")
    cfg["seqs"] = seqs
    cfg["_config_path"] = str(path)
    return cfg


def run_dir(cfg: dict) -> Path:
    return RESULTS_DIR / cfg["run_id"]


def det_cache_dir(cfg: dict) -> Path:
    return CACHE_DIR / "dets" / cfg["detector"]["det_id"]
