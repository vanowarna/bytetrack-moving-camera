"""Project-wide paths, sequence lists and config loading."""
from __future__ import annotations

from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
DATA_ROOT = ROOT / "data" / "mot"
TRAIN_DIR = DATA_ROOT / "train"
VAL_HALF_DIR = DATA_ROOT / "val_half"  # generated by scripts/make_splits.py
CACHE_DIR = ROOT / "cache"  # detection cache (not committed)
RESULTS_DIR = ROOT / "results"

# The 7 unique MOT17 training sequences (FRCNN copies only; the image data is identical across copies).
SEQS = [f"MOT17-{s}-FRCNN" for s in ("02", "04", "05", "09", "10", "11", "13")]

# Camera type, following the MOT16/17 benchmark paper (Milan et al., 2016, Table 2).
STATIC = ["MOT17-02-FRCNN", "MOT17-04-FRCNN", "MOT17-09-FRCNN"]
MOVING = ["MOT17-05-FRCNN", "MOT17-10-FRCNN", "MOT17-11-FRCNN", "MOT17-13-FRCNN"]
GROUPS = {"static": STATIC, "moving": MOVING}


def load_config(path: str | Path) -> dict:
    """Load a run config (YAML). `seqs: all` expands to the 7 sequences."""
    path = Path(path)
    with open(path, encoding="utf-8") as f:
        cfg = yaml.safe_load(f)
    seqs = cfg.get("seqs", "all")
    if seqs == "all":
        seqs = list(SEQS)
    unknown = [s for s in seqs if s not in SEQS]
    if unknown:
        raise ValueError(f"Unknown sequences in {path}: {unknown}")
    cfg["seqs"] = seqs
    cfg["_config_path"] = str(path)
    return cfg


def run_dir(cfg: dict) -> Path:
    return RESULTS_DIR / cfg["run_id"]


def det_cache_dir(cfg: dict) -> Path:
    return CACHE_DIR / "dets" / cfg["detector"]["det_id"]
